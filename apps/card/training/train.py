"""Trains the digit classifier and writes it for the app.

    uv run python train.py data/train.npz data/val.npz ../public/digit-model.js

Weights are stored as int8 with one scale per tensor; the app (reader-core.js)
runs the same layers by hand, so there is no ML runtime to download.
"""

import base64
import json
import sys

import numpy as np
import torch
from torch import nn

import reader

torch.manual_seed(0)


def build() -> nn.Sequential:
    # Layer order and shapes must match runModel in public/reader-core.js.
    return nn.Sequential(
        nn.Conv2d(1, 8, 3, padding=1), nn.ReLU(), nn.MaxPool2d(2),
        nn.Conv2d(8, 16, 3, padding=1), nn.ReLU(), nn.MaxPool2d(2),
        nn.Flatten(),
        nn.Linear(16 * 6 * 6, 48), nn.ReLU(),
        nn.Linear(48, len(reader.CLASSES)),
    )


def load(path):
    d = np.load(path)
    return torch.from_numpy(d["x"]).unsqueeze(1), torch.from_numpy(d["y"])


def accuracy(model, x, y):
    model.eval()
    with torch.no_grad():
        pred = torch.cat([model(x[i:i + 4096]).argmax(1) for i in range(0, len(x), 4096)])
    per_class = {reader.CLASSES[c]: float((pred[y == c] == c).float().mean()) for c in range(len(reader.CLASSES))}
    return float((pred == y).float().mean()), per_class


def quantize(model):
    """int8 weights with a per-tensor scale; biases stay float. Returns the
    tensors for the app and loads the rounded weights back into the model."""
    tensors, blob = [], bytearray()
    for name, p in model.state_dict().items():
        if name.endswith("weight"):
            scale = float(p.abs().max()) / 127
            q = torch.clamp(torch.round(p / scale), -127, 127).to(torch.int8)
            tensors.append({"name": name, "shape": list(p.shape), "scale": scale, "offset": len(blob)})
            blob += q.numpy().tobytes()
            p.copy_(q.float() * scale)
        else:
            tensors.append({"name": name, "shape": list(p.shape), "bias": [round(float(v), 6) for v in p]})
            p.copy_(torch.tensor(tensors[-1]["bias"]))
    return tensors, base64.b64encode(bytes(blob)).decode()


def main():
    train_x, train_y = load(sys.argv[1])
    val_x, val_y = load(sys.argv[2])
    model = build()
    opt = torch.optim.Adam(model.parameters(), lr=2e-3)
    epochs = 12
    sched = torch.optim.lr_scheduler.OneCycleLR(opt, max_lr=3e-3, total_steps=epochs * (len(train_x) // 256 + 1))
    loss_fn = nn.CrossEntropyLoss()
    for epoch in range(epochs):
        model.train()
        perm = torch.randperm(len(train_x))
        for i in range(0, len(train_x), 256):
            idx = perm[i:i + 256]
            xb = train_x[idx]
            # Brightness of print varies; the ink map is already normalised but not exactly.
            xb = xb * torch.empty(len(idx), 1, 1, 1).uniform_(0.7, 1.2)
            opt.zero_grad()
            loss = loss_fn(model(xb), train_y[idx])
            loss.backward()
            opt.step()
            sched.step()
        acc, _ = accuracy(model, val_x, val_y)
        print(f"epoch {epoch + 1}: val {acc:.4f}", file=sys.stderr)
    with torch.no_grad():
        tensors, data = quantize(model)
    acc, per_class = accuracy(model, val_x, val_y)
    print(f"int8: val {acc:.4f}", file=sys.stderr)
    print(json.dumps(per_class, indent=1), file=sys.stderr)
    torch.save(model.state_dict(), "data/model.pt")
    spec = {"glyph": reader.GLYPH, "classes": reader.CLASSES, "tensors": tensors, "data": data}
    with open(sys.argv[3], "w") as f:
        f.write("// Generated by apps/card/training/train.py. Do not edit.\n")
        f.write("(function (root, model) {\n")
        f.write("  if (typeof module === \"object\" && module.exports) module.exports = model;\n")
        f.write("  root.digitModel = model;\n")
        f.write("})(typeof self !== \"undefined\" ? self : globalThis, ")
        f.write(json.dumps(spec, separators=(",", ":")))
        f.write(");\n")


if __name__ == "__main__":
    main()
